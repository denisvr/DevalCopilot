    private static (Project Project, Run Run, Attempt Attempt) CreateClaimedAgentAttempt(string? checkpointFingerprint = null)
    {
        var project = Project.Register(Guid.NewGuid(), "DevalCopilot", $@"C:\repos\{Guid.NewGuid():N}", Now);
        var run = Run.RecordIntent(Guid.NewGuid(), project.Id, 1, "Plan the next increment", Now);
        run.Claim(Now);
        var attempt = Attempt.ClaimAgent(
            Guid.NewGuid(), run.Id, 1, Guid.NewGuid(), Guid.NewGuid(), checkpointFingerprint ?? Fingerprint, Guid.NewGuid(),
            TimeSpan.FromMinutes(10), 262144, 524288, Now);
        return (project, run, attempt);
    }

    [Fact]
    public async Task HandleAsync_records_a_valid_proposal_and_maps_it_to_a_collaboration_message()
    {
        await using var dbContext = fixture.CreateContext();
        var (project, run, attempt) = CreateClaimedAgentAttempt();
        attempt.MarkAgentDispatched(Now);
        dbContext.Projects.Add(project);
        dbContext.Runs.Add(run);
        dbContext.Attempts.Add(attempt);
        await dbContext.SaveChangesAsync(CancellationToken.None);

        var proposal = new ValidatedProposal("Add the ledger table and its query.", ValidStructuredContentJson);
        var handler = new RecordAgentAttemptResultCommandHandler(dbContext, new FixedTimeProvider(Now.AddMinutes(1)));
        var result = await handler.HandleAsync(
            new RecordAgentAttemptResultCommand(run.Id, attempt.Id, AgentOutcome.Proposed, Fingerprint, NoArtifacts, proposal, null),
            CancellationToken.None);

        Assert.True(result.IsSuccess);
        Assert.Equal(AttemptStatus.Completed, result.Value.Status);
        Assert.Equal(AttemptStatus.Completed, attempt.Status);
        Assert.Equal(AgentOutcome.Proposed, attempt.AgentOutcome);

        var message = Assert.Single(dbContext.CollaborationMessages.Where(m => m.RunId == run.Id));
        Assert.Equal(attempt.Id, message.AttemptId);
        Assert.Equal(ParticipantKind.Codex, message.Actor);
        Assert.Equal(ParticipantKind.Claude, message.Recipient);
        Assert.Equal(CollaborationMessageType.Proposal, message.Type);
        Assert.Equal(CollaborationMessage.ProtocolVersionOne, message.ProtocolVersion);
        Assert.Equal(CollaborationMessageProvenance.ProviderObserved, message.Provenance);
        Assert.Equal(proposal.Summary, message.Summary);
        Assert.Equal(proposal.StructuredContentJson, message.StructuredContentJson);
        Assert.Equal(Now.AddMinutes(1), message.OccurredAtUtc);
        Assert.Null(message.InReplyToMessageId);
        // Host-supplied identity: the message id is generated by the handler itself — the
        // command/ValidatedProposal shape carries no provider-supplied identity field at all.
        Assert.NotEqual(Guid.Empty, message.Id);

        var journalEvent = Assert.Single(dbContext.Events.Where(e => e.AttemptId == attempt.Id));
        Assert.Equal(RunEventType.CollaborationMessageRecorded, journalEvent.EventType);
        Assert.Equal(result.Value.LatestEventSequence, journalEvent.Sequence);
        Assert.Contains(message.Id.ToString(), journalEvent.PayloadJson);
    }

