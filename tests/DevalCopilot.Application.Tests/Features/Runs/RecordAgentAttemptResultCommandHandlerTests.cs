    /// <summary>
    /// <see cref="CodexFinalResponseParser"/> is the only production caller that constructs a
    /// <see cref="ValidatedProposal"/>, and it now enforces the exact same
    /// <c>CollaborationMessageContentPolicy</c> bounds and unsafe-content check that
    /// <see cref="CollaborationMessage.Record"/> applies (see
    /// <c>CodexFinalResponseParserTests.TryParse_fails_closed_for_an_overlong_structured_field</c>
    /// and its sibling tests) — a policy-violating provider response never reaches this handler as
    /// a "Proposed" outcome with a non-null <c>Proposal</c> in production. This handler is no
    /// longer a bare pass-through for that hypothetical either: it independently re-validates
    /// <see cref="ValidatedProposal.StructuredContentJson"/> via
    /// <see cref="CollaborationMessageContentPolicy.Validate"/> and maps any resulting
    /// <see cref="ArgumentException"/> to a fail-closed <c>agent_attempts.invalid_proposal_content</c>
    /// result — never an uncaught exception and never a partial mutation.
    /// </summary>
    [Fact]
    public async Task HandleAsync_rejects_a_proposal_with_invalid_structured_content_without_mutating_the_attempt()
    {
        await using var dbContext = fixture.CreateContext();
        var (project, run, attempt) = CreateClaimedAgentAttempt();
        attempt.MarkAgentDispatched(Now);
        dbContext.Projects.Add(project);
        dbContext.Runs.Add(run);
        dbContext.Attempts.Add(attempt);
        await dbContext.SaveChangesAsync(CancellationToken.None);

        var overlongStructuredContent = JsonSerializer.Serialize(new
        {
            scope = new string('x', 950), // Exceeds CollaborationMessageContentPolicy's 900-character field bound.
            implementationSteps = "Add the table then the query",
            risks = "Unbounded content",
            verificationPlan = "Tests",
            escalationPoints = "None expected",
        });
        var proposal = new ValidatedProposal("Summary.", overlongStructuredContent);

        var handler = new RecordAgentAttemptResultCommandHandler(dbContext, new FixedTimeProvider(Now.AddMinutes(1)));
        var result = await handler.HandleAsync(
            new RecordAgentAttemptResultCommand(run.Id, attempt.Id, AgentOutcome.Proposed, Fingerprint, NoArtifacts, proposal, null),
            CancellationToken.None);

        Assert.True(result.IsFailure);
        Assert.Equal("agent_attempts.invalid_proposal_content", Assert.Single(result.Errors).Code);
        Assert.Equal(AttemptStatus.Running, attempt.Status);
        Assert.Null(attempt.AgentOutcome);
        Assert.Empty(dbContext.CollaborationMessages.Where(m => m.RunId == run.Id));
        Assert.Empty(dbContext.Events.Where(e => e.AttemptId == attempt.Id));
    }

